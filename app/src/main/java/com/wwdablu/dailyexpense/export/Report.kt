package com.wwdablu.dailyexpense.export

import com.wwdablu.dailyexpense.data.CategoryTotal
import com.wwdablu.dailyexpense.data.ExpenseRepository
import com.wwdablu.dailyexpense.data.ExpenseWithCategory
import com.wwdablu.dailyexpense.data.PeriodTotals
import kotlinx.coroutines.flow.first
import java.time.LocalDate
import java.time.LocalDateTime
import java.time.format.DateTimeFormatter

const val PDF_MIME_TYPE = "application/pdf"

/** Everything an exported report contains, for one month or one year. */
data class Report(
    val appName: String,
    val isYear: Boolean,
    /** e.g. "November 2026" or "2026". */
    val periodLabel: String,
    val generatedAt: LocalDateTime,
    val totals: PeriodTotals,
    /** Monthly budget, only for month reports. */
    val budget: Long?,
    val spendingByType: List<CategoryTotal>,
    val earningsByType: List<CategoryTotal>,
    /** All entries in the period, oldest first. */
    val entries: List<ExpenseWithCategory>,
) {
    val title get() = "$appName – ${if (isYear) "Yearly" else "Monthly"} Report"

    /** The note every export carries to say the app produced it. */
    val generatedNote: String
        get() = "Generated by the $appName app on " +
            generatedAt.format(DateTimeFormatter.ofPattern("d MMM yyyy 'at' h:mm a"))

    companion object {
        /** Suggested file name, e.g. DailyExpenses_2026-11.pdf or DailyExpenses_2026.pdf. */
        fun fileName(appName: String, day: LocalDate, isYear: Boolean): String {
            val base = appName.replace(" ", "")
            val period = if (isYear) "${day.year}" else day.format(DateTimeFormatter.ofPattern("yyyy-MM"))
            return "${base}_$period.pdf"
        }

        val ENTRY_DATE: DateTimeFormatter = DateTimeFormatter.ofPattern("dd MMM yyyy")

        suspend fun build(repo: ExpenseRepository, appName: String, day: LocalDate, isYear: Boolean, budget: Long?): Report {
            val from = if (isYear) day.withDayOfYear(1) else day.withDayOfMonth(1)
            val to = if (isYear) day.withDayOfYear(day.lengthOfYear()) else day.withDayOfMonth(day.lengthOfMonth())
            val f = from.toEpochDay()
            val t = to.toEpochDay()
            return Report(
                appName = appName,
                isYear = isYear,
                periodLabel = if (isYear) "${day.year}" else day.format(DateTimeFormatter.ofPattern("MMMM yyyy")),
                generatedAt = LocalDateTime.now(),
                totals = repo.observePeriodTotals(f, t).first(),
                budget = if (isYear) null else budget,
                spendingByType = repo.observeSpendingByCategory(f, t).first(),
                earningsByType = repo.observeEarningsByCategory(f, t).first(),
                entries = repo.entriesBetween(f, t),
            )
        }
    }
}
