/** Asks which format to download the period shown in Summary as. [onPick] gets true for CSV. */
@Composable
fun DownloadDialog(periodLabel: String, onPick: (csv: Boolean) -> Unit, onDismiss: () -> Unit) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Download $periodLabel") },
        text = {
            Column {
                FormatOption(Icons.Filled.PictureAsPdf, "PDF report", "Totals, amounts by type and every entry, ready to read or print") {
                    onPick(false)
                }
                FormatOption(Icons.Filled.TableView, "CSV file", "Every entry as rows, to open in a spreadsheet") {
                    onPick(true)
                }
            }
        },
        confirmButton = {},
        dismissButton = { TextButton(onClick = onDismiss) { Text("Cancel") } },
    )
}

@Composable
private fun FormatOption(icon: ImageVector, title: String, subtitle: String, onClick: () -> Unit) {
    Row(
        Modifier.fillMaxWidth().clip(RoundedCornerShape(12.dp)).clickable(onClick = onClick).padding(vertical = 12.dp, horizontal = 8.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Icon(icon, null, tint = MaterialTheme.colorScheme.primary)
        Spacer(Modifier.width(16.dp))
        Column {
            Text(title, style = MaterialTheme.typography.titleMedium)
            Text(subtitle, style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}
